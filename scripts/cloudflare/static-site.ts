/**
 * Prepares a Next static export (`output: 'export'`) to be served as Workers static
 * assets, routing requests the way the Go daemons route the same export in
 * internal/nextjs: an exact page first, then a dynamic page whose segments match, and
 * otherwise 404.html.
 *
 * A dynamic page exports to a file that keeps its brackets, such as `wallets/[id].html`,
 * and Next reads the real segment values from the address bar once the page loads, so
 * serving that file for `/wallets/abc` is all the routing it needs. That is a 200
 * rewrite in `_redirects`. The target has its brackets percent-encoded, because a
 * target with literal brackets answers with a 307 to the bracketed path, and that path
 * then redirects to itself.
 *
 * Workers applies `_redirects` before looking for a file, so a rewrite for
 * `/wallets/:id` would also catch a real page at `/wallets/new`, which Next and the Go
 * router both serve as itself. No app has a page there today, and the plan refuses to
 * build one that does rather than serve the wrong page.
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join, relative, sep } from 'node:path'

const generatedHeader = '# Generated by scripts/cloudflare/static-site.ts'

export type Rewrite = {
  /** `_redirects` source pattern, such as `/wallets/:id`. */
  pattern: string
  /** The exported page, such as `/wallets/%5Bid%5D`. */
  target: string
}

/**
 * Works out the `_redirects` rewrites for a site from the paths of its exported HTML
 * files, relative to the site root and using `/`. They come back in file order, since
 * Cloudflare applies the first rule that matches.
 */
export function planRewrites(htmlFiles: string[]): Rewrite[] {
  const rewrites: (Rewrite & { rank: number[] })[] = []

  for (const file of htmlFiles) {
    if (!file.includes('[')) continue
    const segments = file.replace(/\.html$/, '').split('/')
    const target = `/${segments.map(encodeBrackets).join('/')}`

    const last = segments[segments.length - 1]
    const prefix = segments.slice(0, -1).map(toPattern)
    const patterns = last.startsWith('[[...')
      ? [prefix, [...prefix, '*']]
      : [[...prefix, toPattern(last)]]

    for (const parts of patterns) {
      const fixed = parts.filter((p) => p !== '*')
      rewrites.push({
        pattern: `/${parts.join('/')}`,
        target,
        // Longer and more literal patterns first, and a splat after the same path
        // without one, so a general rule never shadows a specific one.
        rank: [
          fixed.length,
          fixed.filter((p) => !p.startsWith(':')).length,
          parts.length - fixed.length,
        ],
      })
    }
  }

  for (const file of htmlFiles) {
    if (file.includes('[')) continue
    const path = `/${file.replace(/\.html$/, '').replace(/(^|\/)index$/, '')}`
    const rewrite = rewrites.find((r) => patternMatches(r.pattern, path))
    if (rewrite) {
      throw new Error(
        `${rewrite.pattern} would also catch the page at ${path}, because Workers ` +
          'applies _redirects before serving files',
      )
    }
  }

  rewrites.sort(
    (a, b) =>
      b.rank[0] - a.rank[0] ||
      b.rank[1] - a.rank[1] ||
      a.rank[2] - b.rank[2] ||
      a.pattern.localeCompare(b.pattern),
  )
  return rewrites.map(({ pattern, target }) => ({ pattern, target }))
}

function toPattern(segment: string): string {
  if (segment.startsWith('[...') || segment.startsWith('[[...')) return '*'
  const param = /^\[(.+)\]$/.exec(segment)
  return param ? `:${param[1]}` : segment
}

function encodeBrackets(segment: string): string {
  return segment.replaceAll('[', '%5B').replaceAll(']', '%5D')
}

/** Whether a `_redirects` pattern such as `/wallets/:id` or `/a/*` matches a path. */
function patternMatches(pattern: string, path: string): boolean {
  const want = pattern.split('/').filter(Boolean)
  const have = path.split('/').filter(Boolean)
  for (let i = 0; i < want.length; i++) {
    // A splat needs at least one segment.
    if (want[i] === '*') return have.length > i
    if (i >= have.length) return false
    if (!want[i].startsWith(':') && want[i] !== have[i]) return false
  }
  return want.length === have.length
}

function htmlFilesUnder(root: string): string[] {
  const files: string[] = []
  const walk = (dir: string) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const path = join(dir, entry.name)
      if (entry.isDirectory()) walk(path)
      else if (entry.name.endsWith('.html'))
        files.push(relative(root, path).split(sep).join('/'))
    }
  }
  walk(root)
  return files.sort()
}

// Refuses to overwrite a `_redirects` or `_headers` that came from the app's public/
// folder, since those would be the app's own rules.
function writeGenerated(path: string, body: string) {
  if (
    existsSync(path) &&
    !readFileSync(path, 'utf8').startsWith(generatedHeader)
  ) {
    throw new Error(`${path} exists and was not generated here`)
  }
  writeFileSync(path, `${generatedHeader}\n${body}`)
}

/**
 * Writes `_redirects` and `_headers` into an export. Running it twice gives the same
 * result.
 */
export function prepareStaticSite(root: string): Rewrite[] {
  const rewrites = planRewrites(htmlFilesUnder(root))
  writeGenerated(
    join(root, '_redirects'),
    rewrites.map((r) => `${r.pattern} ${r.target} 200\n`).join(''),
  )
  // Next puts a content hash in every file name under /_next/static, so a cached
  // copy can never be stale.
  writeGenerated(
    join(root, '_headers'),
    '/_next/static/*\n  Cache-Control: public, max-age=31536000, immutable\n',
  )
  return rewrites
}
